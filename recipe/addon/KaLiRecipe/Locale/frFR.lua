-- French's own typography, as the game's French prints it: a no-break space before : ; ? ! and », after «, and
-- between a figure and %; the apostrophe ’.
local NBSP = ns.NBSP
ns.Typeset(OWN.frFR, function(s)
    -- one rule a mark: a class of bytes would take « for », which share their first byte
    s = s:gsub(" ([:;!?])", NBSP .. "%1"):gsub(" »", NBSP .. "»"):gsub("« ", "«" .. NBSP)
    s = s:gsub("(%d) %%", "%1" .. NBSP .. "%%"):gsub("(%%[%-%d%.]*[A-Za-z]) %%%%", "%1" .. NBSP .. "%%%%")
    return (s:gsub("([A-Za-z])'", "%1’"))
end)

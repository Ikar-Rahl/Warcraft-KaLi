-- German's own typography (Duden): a no-break space between a figure and %. Quotes „…“, written as they are.
local NBSP = ns.NBSP
ns.Typeset(OWN.deDE, function(s)
    return (s:gsub("(%d) %%", "%1" .. NBSP .. "%%"):gsub("(%%[%-%d%.]*[A-Za-z]) %%%%", "%1" .. NBSP .. "%%%%"))
end)

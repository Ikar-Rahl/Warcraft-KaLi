    T.Eq(m:Info(R.steak).req, nil, "a trainer's recipe: no rank until a trainer gives it")
    T.Eq(m:Info(R.steak).item, nil, "and no item")
    T.Eq(m:Info(R.bracer).req, 1, "one the game teaches on its own: the rank its table gives")
    T.Eq(m:Info(1245250).req, 1, "Forever's « Élixir de Force mineure », taught with Alchemy: rank 1")
end)


T.Add("Model", "the two counts, and the three sections", function()
    local m, db = T.NewBook()
    m:Note(R.ribs, T.Vendor(), 1)
    m:Note(R.stew, T.Vendor(), 1)
    m:Note(R.robe, T.Vendor(), 1)

local T = KaLiRecipeTests
local ns = KaLiRecipeDev.ns
local R, I = T.R, T.ITEM

T.Add("Model", "nothing never met shows: the data alone puts nothing in the notebook", function()
    local m = T.NewBook()
    T.Eq(#m:SpellsOf(185), 0, "no cooking recipe")
    T.Eq(m:Total(), 0, "an empty notebook")
    T.Eq(#m:MadeBy(I.boarRibs), 0, "no « Fabriqué par » for an unmet recipe")
    local known, seen = m:UsedIn(I.boarMeat)
    T.Eq(#known + #seen, 0, "no « Utilisé dans » for an unmet recipe")
end)

T.Add("Model", "a recipe item gives its recipe, and the recipe its data", function()

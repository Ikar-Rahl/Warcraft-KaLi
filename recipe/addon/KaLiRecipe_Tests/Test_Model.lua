T.Add("Model", "categories in the game's order, « Divers » last, recipes by rank then name", function()
    local m = T.NewBook()
    local groups = m:ByCategory({ R.stew, R.ribs, R.steak, 818 })
    T.True(#groups >= 2, "at least two groups")
    T.Eq(groups[#groups].id, nil, "the recipe outside the tree (818, a campfire) under « Divers », last")
    T.Eq(groups[#groups].name, ns.G("MISCELLANEOUS", "Divers"), "named as the game names it")
    for _, g in ipairs(groups) do
        for i = 2, #g.spells do
            T.True((m:Info(g.spells[i - 1]).req or 0) <= (m:Info(g.spells[i]).req or 0), "ranks in order in " .. g.name)
        end
    end
end)

T.Add("Model", "search ignores case and accents, in names and reagents; filters combine", function()
    local m, db, game = T.NewBook()
    m:Note(R.ribs, T.Vendor(), 1)
    m:Note(R.stew, { k = "ah" }, 1)
    T.True(m:Passes(R.ribs, "me", "COTES"), "« COTES » finds « Côtes »")
    T.True(m:Passes(R.ribs, "me", "biere de"), "a reagent's name finds it")
    T.Eq(m:Passes(R.ribs, "me", "ragoût"), false, "another name doesn't")
    T.True(m:Passes(R.ribs, "me", "", { sources = { vendor = true } }), "seen at a vendor")
    T.Eq(m:Passes(R.stew, "me", "", { sources = { vendor = true } }), false, "only at the auction house")
    T.True(m:Passes(R.ribs, "me", "", { skillUp = true }), "can raise the skill")
    T.Eq(m:Passes(R.ribs, "me", "", { makeable = true }), false, "no reagents in the bags")
    game.counts[I.boarMeat], game.counts[I.beer] = 1, 1
    T.True(m:Passes(R.ribs, "me", "", { makeable = true }), "with the reagents")
    T.Eq(m:Passes(R.ribs, "me", "", { owned = { mine = true } }), false, "not held")
    db.chars.me.bags[I.ribs] = 1
    m:Invalidate()
    T.True(m:Passes(R.ribs, "me", "", { owned = { mine = true } }), "held")
    T.True(ns.Model.Filtered({ owned = { alt = true } }), "a filter is on")
    T.Eq(ns.Model.Filtered({ cats = {}, sources = {} }), false, "empty sets aren't a filter")
end)


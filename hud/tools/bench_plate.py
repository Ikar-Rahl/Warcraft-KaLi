"""The plate the addon draws on Ikar's layout (the fake game's, from his probe), for the borders bench, once for each of
the bench's looks (the windows it hugs and the minimap's ring follow the border's depth): its outline as the frames
give it (the bench smooths it for its corners, Geometry.Smooth ported), its dome and slots; and for the shipped look,
Geometry.Path's own outline to check the port against; written to hud/bench/js/plate-data.js.

Run with: python -I hud/tools/bench_plate.py
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import make_media  # noqa: E402
import run_tests  # noqa: E402

OUT = HERE.parent / "bench/js/plate-data.js"


def plain(value):
    """A Lua table as JSON values: lists for arrays, dicts otherwise."""
    if hasattr(value, "items"):
        items = dict(value.items())
        if items and all(isinstance(k, int) for k in items):
            return [plain(items[k]) for k in sorted(items)]
        return {str(k): plain(v) for k, v in items.items()}
    return value


def main():
    lua, load_addon = run_tests.runtime()
    load_addon("KaLiHUD")
    lua.execute('FakeWoW.Fire("ADDON_LOADED", "KaLiHUD"); FakeWoW.Fire("PLAYER_LOGIN");'
                'FakeWoW.Fire("PLAYER_ENTERING_WORLD"); FakeWoW.RunTimers()')
    grab = lua.eval("""function(edge, out)
        local ns = KaLiHUDDev.ns
        local shipped = { edge = ns.LOOK.edge, out = ns.LOOK.out }
        ns.LOOK.edge, ns.LOOK.out = edge or shipped.edge, out or shipped.out
        local art = ns.Plate.Layout()
        ns.LOOK.edge, ns.LOOK.out = shipped.edge, shipped.out
        local slots, segs = {}, {}
        for i, s in ipairs(art.slots) do
            slots[i] = { key = s.key, kind = s.kind, x = s.x, y = s.y, w = s.w, h = s.h }
        end
        for i, s in ipairs(art.outline) do
            segs[i] = { x0 = s.x0, x1 = s.x1, top = s.top, dome = s.dome or false }
        end
        return { segs = segs, dome = art.dome, slots = slots }, art
    end""")
    looks = {}
    for P in make_media.looks():
        looks[P["id"]] = plain(grab(make_media.look_edge(P), P["shadow"])[0])
    _, art = grab(None, None)
    check = lua.eval("""function(art)
        local ns = KaLiHUDDev.ns
        local G, o = ns.Geometry, ns.db.options
        return { id = ns.LOOK.id, e = ns.Border.Profile().e, style = o.cornerStyle,
            path = G.Path(G.Pieces(art.segs, art.dome, 0, ns.Plate.Corners(o)), art.W) }
    end""")(art)
    o = lua.eval("KaLiHUDDev.ns.db.options")
    data = {"W": art.W, "H": lua.eval("UIParent:GetHeight()"), "T": art.T, "corner": o.corner, "fillet": o.fillet,
            "looks": looks, "check": plain(check)}
    OUT.write_text("// Generated by hud/tools/bench_plate.py. Don't edit.\nwindow.HUD_PLATE = "
                   + json.dumps(data) + ";\n", encoding="utf-8", newline="\n")
    print("written", OUT, len(looks), "looks,", len(data["check"]["path"]) // 2, "points to check")


if __name__ == "__main__":
    main()

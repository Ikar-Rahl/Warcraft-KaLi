"""The zones' levels as Forever's own Group Finder suggests them, for the zone's levels on the bar and under fishing's
tooltip (UI/Hub/Infos/World.lua, UI/Hub/Infos/Skills.lua; Ikar 2026-11-18: "Add the table, scrap the data", "for
forever, be carrefull"). Writes Data/Zones.lua.

The game gives no zone a level range otherwise: every zone's UiMap and AreaTable row has none on Forever, so
C_Map.GetMapLevels gives nothing (nor on Classic Era, whose UiMap's LevelRangeMin and LevelRangeMax are all 0). Its
Group Finder lists one activity a zone in its « Quests & Zones » category (DB2 GroupFinderActivity, category 116), each
with a level from (MinLevel) and a level suggested up to (MaxLevelSuggestion): Forever's own ranges, not Classic's
(Elwynn Forest 1-14, Westfall 8-24, wider than Classic's 1-10 and 10-20), with its new zones' (Riverglades, Zephras
Isle, Mount Hyjal). A zone it doesn't list (the cities, Moonglade, Deadwind Pass, Shen'dralas) has none.
Each activity is matched to the zone maps (UiMap, type 3) of its English name, or of the name ALIASES gives where
the Group Finder words it otherwise; each must match one at least, and no map two.

The tables beyond UiMap come from wago.tools: --fetch downloads those missing into the reference copies' db2 folder
for this build.

Run with: python -I hud/tools/make_zones.py [--fetch]
"""
import csv
import sys
import urllib.request
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools"))
from kali.art import BUILD  # noqa: E402
from kali.paths import REFERENCE  # noqa: E402

ADDON = ROOT / "hud/addon/KaLiHUD"
TARGET = ADDON / "Data/Zones.lua"
DB2 = REFERENCE / "db2" / BUILD
FETCHED = ("GroupFinderActivity", "GroupFinderCategory")
# The Group Finder's category of the zones' quests, by its English name in this build.
QUESTS_AND_ZONES = 116
QUESTS_AND_ZONES_NAME = "Quests & Zones"
# A zone the Group Finder names otherwise than its map does.
ALIASES = {"Hinterlands": "The Hinterlands"}
# UiMap's type of a zone (Enum.UIMapType.Zone).
ZONE = "3"


def fetch():
    """The tables missing from the reference copies, downloaded for this build."""
    DB2.mkdir(parents=True, exist_ok=True)
    for table in FETCHED:
        path = DB2 / f"{table}.csv"
        if not path.exists():
            url = f"https://wago.tools/db2/{table}/csv?build={BUILD}"
            # a browser's name: the site refuses Python's own (403); Ikar 2026-11-18: "I allow, go scrapp"
            request = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0 (generic data script)"})
            with urllib.request.urlopen(request, timeout=120) as r:
                path.write_bytes(r.read())
            print(f"fetched: {table}")


def rows(table):
    path = DB2 / f"{table}.csv"
    if not path.exists():
        sys.exit(f"{path} is missing: run python -I hud/tools/make_zones.py --fetch, or save "
                 f"https://wago.tools/db2/{table}/csv?build={BUILD} there")
    with open(path, encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def levels():
    """Each zone map the Group Finder gives levels for: (its name, its lowest level, its highest suggested)."""
    categories = {r["ID"]: r["Name_lang"] for r in rows("GroupFinderCategory")}
    found_name = categories.get(str(QUESTS_AND_ZONES))
    assert found_name == QUESTS_AND_ZONES_NAME, \
        f"category {QUESTS_AND_ZONES} isn't {QUESTS_AND_ZONES_NAME!r} in {BUILD}: {found_name!r}"
    maps = defaultdict(list)
    for r in rows("UiMap"):
        if r["Type"] == ZONE:
            maps[r["Name_lang"]].append(int(r["ID"]))
    out = {}
    for r in rows("GroupFinderActivity"):
        if r["GroupFinderCategoryID"] != str(QUESTS_AND_ZONES):
            continue
        name = r["FullName_lang"]
        zone = ALIASES.get(name, name)
        found = maps.get(zone)
        assert found, f"the Group Finder's {name!r} is no zone map of {BUILD}"
        low, high = int(r["MinLevel"] or 0), int(r["MaxLevelSuggestion"] or 0)
        assert 1 <= low <= high, f"the Group Finder's {name!r} has no levels in {BUILD}: {low}-{high}"
        for m in found:
            assert m not in out, f"two of the Group Finder's activities for the map {m} ({zone}) in {BUILD}"
            out[m] = (zone, low, high)
    return dict(sorted(out.items()))


def build():
    found = levels()
    lines = [
        f"-- Generated by hud/tools/make_zones.py from Forever's game data ({BUILD}): the zones' levels as its own Group",
        "-- Finder suggests them (GroupFinderActivity's « Quests & Zones »: MinLevel, MaxLevelSuggestion), by the zone's",
        "-- map (UiMap). A zone it doesn't list has none. Don't edit.",
        "local _, ns = ...",
        "",
        "ns.ZONE_LEVELS = {",
    ]
    lines += [f"    [{m}] = {{ {low}, {high} }}, -- {zone}" for m, (zone, low, high) in found.items()]
    lines += ["}", ""]
    return "\n".join(lines), len(found)


def main():
    if "--fetch" in sys.argv:
        fetch()
    text, count = build()
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    print(f"written: Data/Zones.lua, {count} zone maps")


if __name__ == "__main__":
    main()

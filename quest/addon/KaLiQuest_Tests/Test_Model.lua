T.Add("Model", "deleting untracks its quests and can be undone in place", function()
    local m, w, db = T.NewModel()
    local a, b, c = m:CreateGroup("A"), m:CreateGroup("B"), m:CreateGroup("C")
    m:MoveQuest(4, b.id)
    m:MoveQuest(5, b.id)
    db.open.groups[b.id] = false
    m:DeleteGroup(b.id)
    T.Eq(#db.groups, 2, "gone")
    T.True(not w:IsWatched(4) and not w:IsWatched(5), "untracked")
    local back = m:UndoDelete()
    T.Eq(db.groups[2], back, "back in its place")
    T.List(back.quests, { 4, 5 }, "with its quests")
    T.True(w:IsWatched(4) and w:IsWatched(5), "tracked again")
    T.Eq(db.open.groups[back.id], nil, "closed as it was")
    T.Eq(m.deleted, nil, "undo used up")
    T.True(a and c, "the others stay")
end)


T.Add("Model", "several quests move together, in order, and an index skips the moving ones", function()
    local m, w = T.NewModel()
    local a, b = m:CreateGroup("A"), m:CreateGroup("B")
    for _, id in ipairs({ 1, 2, 3, 4 }) do
        m:MoveQuest(id, a.id)
    end
    T.True(m:MoveQuests({ 4, 2 }, b.id), "moved")
    T.List(b.quests, { 4, 2 }, "in the order given")
    T.List(a.quests, { 1, 3 }, "gone from A")
    m:MoveQuests({ 4, 2 }, a.id, 2)
    T.List(a.quests, { 1, 4, 2, 3 }, "before A's second")
    m:MoveQuests({ 4, 2 }, a.id, 3)
    T.List(a.quests, { 1, 3, 4, 2 }, "the index counts only the quests that stay")
    m:MoveQuests({ 1, 3 }, nil)
    T.List(a.quests, { 4, 2 }, "taken out")
    T.True(not w:IsWatched(1) and not w:IsWatched(3) and w:IsWatched(4), "and untracked")
    w.combat = true
    local _, reason = m:MoveQuests({ 4 }, b.id)
    T.Eq(reason, "combat", "refused in combat")
    T.List(b.quests, {}, "nothing moved")
end)


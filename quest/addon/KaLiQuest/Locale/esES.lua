-- Spanish's own typography (the RAE): a no-break space between a figure and %. Quotes «…», written as they are.
local NBSP = ns.NBSP
ns.Typeset(OWN.esES, function(s)
    return (s:gsub("(%d) %%", "%1" .. NBSP .. "%%"):gsub("(%%[%-%d%.]*[A-Za-z]) %%%%", "%1" .. NBSP .. "%%%%"))
end)

"""Generate KaLi Quest's map-to-zone table from the game's own UiMap tables.

Writes quest/addon/KaLiQuest/Data/Maps.lua: each zone or dungeon map's area, when the map shows a single top-level area,
so the API check can hold GetZoneText() against that area's name in game. No API links a map to its area.

Run with: python -I quest/tools/gen_map_areas.py
"""
import csv
import sys
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8")
sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "tools"))
from kali.paths import QUEST, REFERENCE  # noqa: E402
DB2 = max((REFERENCE / "db2").iterdir())
OUT = QUEST / "addon/KaLiQuest/Data/Maps.lua"
ZONE, DUNGEON = 3, 4


def rows(name):
    with open(DB2 / name, encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


kinds = {int(r["ID"]): int(r["Type"]) for r in rows("UiMap.csv")}
parents = {int(r["ID"]): int(r["ParentAreaID"]) for r in rows("AreaTable.csv")}
areas = {}
for r in rows("UiMapAssignment.csv"):
    ui_map, area = int(r["UiMapID"]), int(r["AreaID"])
    if kinds.get(ui_map) in (ZONE, DUNGEON) and parents.get(area) == 0:
        areas.setdefault(ui_map, set()).add(area)
single = {ui_map: next(iter(found)) for ui_map, found in areas.items() if len(found) == 1}

lines = [
    f"-- Generated by quest/tools/gen_map_areas.py from the game's UiMap tables ({DB2.name}). Don't edit by hand.",
    "local _, ns = ...",
    "",
    "-- Zone and dungeon maps -> the top-level area each shows, for the API check: GetZoneText() is that area's name.",
    "ns.MAP_AREAS = {",
]
lines += [f"    [{ui_map}] = {area}," for ui_map, area in sorted(single.items())]
lines += ["}", ""]
OUT.write_text("\n".join(lines), encoding="utf-8")
print(f"{OUT}: {len(single)} maps, {len(areas) - len(single)} left out as they show several areas")

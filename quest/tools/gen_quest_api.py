"""Generates quest/docs/quest-api-inventory.md from Blizzard's API documentation in the reference copies' wow-ui-source.

Run after a game patch, once the reference copies' wow-ui-source is updated:
    python -I quest/tools/gen_quest_api.py
"""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "tools"))
from kali.paths import QUEST, REFERENCE  # noqa: E402
DOC_DIR = REFERENCE / "wow-ui-source/Interface/AddOns/Blizzard_APIDocumentationGenerated"
GLOBALS = REFERENCE / "BlizzardInterfaceResources/Resources/GlobalAPI.lua"
OUT = QUEST / "docs/quest-api-inventory.md"

SYSTEMS = ["QuestLog", "SuperTrackManager", "QuestInfoSystem", "QuestLineUI", "QuestHubUI", "QuestTaskInfo",
           "QuestOffer", "QuestItemUse", "QuestSession"]
TOKEN = re.compile(r'--[^\n]*|\s+|"(?:[^"\\]|\\.)*"|-?\d+(?:\.\d+)?|[A-Za-z_][A-Za-z0-9_.]*|[{}=,;]', re.S)
ORDINARY = {"Name", "Type", "Namespace", "Arguments", "Returns", "Payload", "LiteralName", "Documentation", "Fields",
            "SynchronousEvent", "UniqueEvent", "MayReturnNothing", "Environment"}


def tokenize(text):
    tokens, pos = [], 0
    while pos < len(text):
        m = TOKEN.match(text, pos)
        if not m:
            pos += 1
            continue
        pos = m.end()
        t = m.group(0)
        if not t.isspace() and not t.startswith("--"):
            tokens.append(t)
    return tokens


def parse_table(tokens, i):
    arr, obj = [], {}
    while tokens[i] != "}":
        if tokens[i] in ",;":
            i += 1
        elif tokens[i + 1] == "=" and tokens[i] != "{":
            key = tokens[i]
            obj[key], i = parse_value(tokens, i + 2)
        else:
            value, i = parse_value(tokens, i)
            arr.append(value)
    return (obj if obj else arr), i + 1


def parse_value(tokens, i):
    t = tokens[i]
    if t == "{":
        return parse_table(tokens, i + 1)
    if t.startswith('"'):
        return t[1:-1], i + 1
    if t in ("true", "false"):
        return t == "true", i + 1
    return t, i + 1


def load_docs():
    docs = {}
    for path in sorted(DOC_DIR.glob("*.lua")):
        text = path.read_text(encoding="utf-8", errors="replace")
        table, _ = parse_table(tokenize(text[text.find("{"):]), 1)
        if isinstance(table, dict) and table.get("Name"):
            docs[table["Name"]] = table
    return docs


def fields(items):
    if not isinstance(items, list):
        return ""
    return ", ".join(a.get("Name", "?") + ("?" if a.get("Nilable") else "") for a in items if isinstance(a, dict))


def flags(entry):
    return ", ".join(f"{k}={v}" for k, v in entry.items() if k not in ORDINARY)


def undocumented_globals(docs):
    documented = set()
    for system in docs.values():
        for f in system.get("Functions") or []:
            if isinstance(f, dict):
                documented.add(f.get("Name"))
    names = re.findall(r'^\s*"([A-Za-z_]\w*)",', GLOBALS.read_text(encoding="utf-8", errors="replace"), re.M)
    return sorted(n for n in set(names) if "quest" in n.lower() and n not in documented)


def main():
    docs = load_docs()
    lines = [
        "# Quest API inventory",
        "",
        "Generated by `quest/tools/gen_quest_api.py` from Blizzard's own API documentation on the `forever` branch.",
        "Do not edit by hand.",
        "",
        "`?` marks a nilable argument or return. An empty flags column means Blizzard flags nothing notable.",
        "",
        "`SecretArguments=AllowedWhenUntainted` means a *secret* value may only be passed by untainted code. Quest IDs "
        "are not secret, so this does not limit normal calls.",
        "",
    ]
    total = 0
    for name in SYSTEMS:
        system = docs.get(name)
        if not system:
            lines += [f"## {name}", "", "Not found in this build.", ""]
            continue
        functions = [f for f in system.get("Functions") or [] if isinstance(f, dict)]
        events = [e for e in system.get("Events") or [] if isinstance(e, dict)]
        total += len(functions)
        ns = system.get("Namespace") or ""
        lines += [f"## {name} ({ns or 'globals'}): {len(functions)} functions, {len(events)} events", ""]
        if functions:
            lines += ["| Function | Arguments | Returns | Flags |", "| --- | --- | --- | --- |"]
            for f in functions:
                prefix = f"{ns}." if ns and f.get("Namespace") != "" else ""
                lines.append(f"| `{prefix}{f['Name']}` | {fields(f.get('Arguments'))} | {fields(f.get('Returns'))} | {flags(f)} |")
            lines.append("")
        if events:
            lines += ["| Event | Payload |", "| --- | --- |"]
            for e in events:
                lines.append(f"| `{e.get('LiteralName') or e.get('Name')}` | {fields(e.get('Payload'))} |")
            lines.append("")
    legacy = undocumented_globals(docs)
    lines += [
        f"## Undocumented quest globals: {len(legacy)}",
        "",
        "These exist in the client but Blizzard's documentation does not describe them, so their restrictions are "
        "**unknown from the docs**. Source: `BlizzardInterfaceResources`, which is one build behind the client.",
        "",
        ", ".join(f"`{n}`" for n in legacy),
        "",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT} with {total} documented functions and {len(legacy)} undocumented globals")


if __name__ == "__main__":
    main()

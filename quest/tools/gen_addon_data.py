"""Generate KaLi Quest's classification data from the game's own tables.

Writes quest/addon/KaLiQuest/Data/Sorts.lua:
  - QuestSort IDs for classes, professions, events and the rest, with their names per client language,
    because the quest log's headers use these names and no API returns them.
  - The area IDs of instance and battleground headers, translated in game by C_Map.GetAreaInfo.

Run with: python -I quest/tools/gen_addon_data.py
The instance list comes from the headers vanilla quests use, as measured by research/quest_categories_test.py, and every
top-level area of a dungeon or raid map, for Forever's new dungeons.
"""
import contextlib
import csv
import io
import runpy
import sys
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8")
HERE = Path(__file__).resolve().parent
# A real text stream, because the script being run calls reconfigure on stdout.
with contextlib.redirect_stdout(io.TextIOWrapper(io.BytesIO(), encoding="utf-8")):
    cats = runpy.run_path(str(HERE / "research/quest_categories_test.py"))

ROOT = cats["ROOT"]
DB2 = cats["REFERENCE"] / "db2/1.60.1.70790"
OUT = ROOT / "quest/addon/KaLiQuest/Data/Sorts.lua"

CLASS_SORTS, TRADE_SORTS, EVENT_SORTS = cats["CLASS_SORTS"], cats["TRADE_SORTS"], cats["EVENT_SORTS"]
vanilla, num, ZONE = cats["vanilla"], cats["num"], cats["ZONE_OR_SORT"]
area_kind, battleground_areas = cats["area_kind"], cats["battleground_areas"]


def sort_names(path):
    with open(path, encoding="utf-8", newline="") as f:
        return {int(r["ID"]): r["SortName_lang"] for r in csv.DictReader(f)}


# The client languages the addon speaks; every other falls back to enUS. The German and Spanish tables came from
# wago.tools with &locale= on 2026-11-13, as the French one before (docs/quest-data-sources.md).
LOCALES = ("enUS", "frFR", "deDE", "esES", "esMX")
names = {locale: sort_names(DB2 / ("QuestSort.csv" if locale == "enUS" else f"QuestSort.{locale}.csv"))
         for locale in LOCALES}
used_areas = {num(q, ZONE) for q in vanilla.values() if num(q, ZONE) > 0}
# Forever adds dungeons no vanilla quest uses, such as La salle des Thanes, so every top-level area of a dungeon or
# raid map counts too, unless an outdoor area shares its French name.
area_rows, instance_type, area_fr = cats["area_rows"], cats["instance_type"], cats["area_fr"]
on_instance = {int(a["ID"]) for a in area_rows if instance_type.get(int(a["ContinentID"]), 0) in (1, 2)}
outdoor_fr = {area_fr.get(int(a["ID"])) for a in area_rows if a["ParentAreaID"] == "0" and int(a["ID"]) not in on_instance}
top_instance = {int(a["ID"]) for a in area_rows if a["ParentAreaID"] == "0" and int(a["ID"]) in on_instance
                and area_fr.get(int(a["ID"])) not in outdoor_fr}
instances = sorted(z for z in used_areas | top_instance if area_kind.get(z) in (1, 2) and z not in battleground_areas)
battlegrounds = sorted(z for z in used_areas if z in battleground_areas)


def kind(sort_id):
    if sort_id in CLASS_SORTS:
        return "class"
    if sort_id in TRADE_SORTS:
        return "profession"
    if sort_id in EVENT_SORTS:
        return "event"
    return "misc"


def lua_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


lines = [
    "-- Generated by quest/tools/gen_addon_data.py from the game's QuestSort and AreaTable. Don't edit by hand.",
    "local _, ns = ...",
    "",
    "-- QuestSort ID -> what the header means. Unused \"REUSE\" rows are left out.",
    "ns.SORT_KIND = {",
]
for sort_id in sorted(names["enUS"]):
    if names["enUS"][sort_id].startswith("REUSE"):
        continue
    lines.append(f"    [{sort_id}] = \"{kind(sort_id)}\", -- {names['enUS'][sort_id]}")
lines += ["}", "", "-- The headers' names, per client language. Languages missing here fall back to enUS.", "ns.SORT_NAMES = {"]
for locale in LOCALES:
    lines.append(f"    {locale} = {{")
    for sort_id in sorted(names[locale]):
        if names["enUS"].get(sort_id, "").startswith("REUSE"):
            continue
        lines.append(f"        [{sort_id}] = {lua_string(names[locale][sort_id])},")
    lines.append("    },")
lines += [
    "}",
    "",
    f"-- Instance headers: {len(instances)} area IDs, named in game by C_Map.GetAreaInfo.",
    "ns.INSTANCE_AREAS = { " + ", ".join(map(str, instances)) + " }",
    "ns.BATTLEGROUND_AREAS = { " + ", ".join(map(str, battlegrounds)) + " }",
    "",
]
OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
print(f"{OUT}: {len(instances)} instances, {len(battlegrounds)} battlegrounds, {len(names['enUS'])} sorts")
